// The Python stage owns the response module groups and records them here.
const RESPONSE_GROUPS_KEYWORD = "x-haute-response-groups";
const TYPE_ROOT_NAME = "HauteApiContractRoots";

function responseValidatorModules(schema) {
  const groups = schema[RESPONSE_GROUPS_KEYWORD];
  if (!groups || typeof groups !== "object" || Array.isArray(groups)) {
    throw new Error(`Contract bundle is missing its ${RESPONSE_GROUPS_KEYWORD} map`);
  }
  return Object.entries(groups).map(([group, definitionNames]) => {
    if (
      !/^[a-z][a-z0-9-]*$/.test(group)
      || !Array.isArray(definitionNames)
      || definitionNames.length === 0
      || definitionNames.some((name) => typeof name !== "string" || !/^[A-Z][A-Za-z0-9]*$/.test(name))
    ) {
      throw new Error(`Invalid response contract group: ${group}`);
    }
    return {
      validatorFilename: `api-contracts.${group}.validators.mjs`,
      declarationFilename: `api-contracts.${group}.validators.d.mts`,
      allErrors: false,
      validators: definitionNames.map((definitionName) => ({
        definitionName,
        exportName: `validate${definitionName}`,
      })),
    };
  });
}

export function validatorModules(schema) {
  return [...PILOT_VALIDATOR_MODULES, ...responseValidatorModules(schema)];
}

function withBanner(contents) {
  return `${GENERATED_BANNER}${contents.trimEnd()}\n`;
}

function parseOptions(argv) {
  let check = false;
  let outputDirectory = DEFAULT_OUTPUT_DIRECTORY;
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--output-dir") {
      const value = argv[index + 1];
      if (!value) throw new Error("--output-dir requires a directory");
      outputDirectory = path.resolve(value);
      index += 1;
    } else throw new Error(`Unknown argument: ${argument}`);
  }
  return { check, outputDirectory };
}

function compactNullableSchemas(value) {
  if (Array.isArray(value)) {
    return value.map(compactNullableSchemas);
  }
  if (!value || typeof value !== "object") {
    return value;
  }

  const compacted = Object.fromEntries(
    Object.entries(value).map(([key, nestedValue]) => [key, compactNullableSchemas(nestedValue)]),
  );
  const alternatives = compacted.anyOf;
  if (!Array.isArray(alternatives) || alternatives.length !== 2) {
    return compacted;
  }
  const nullIndex = alternatives.findIndex((alternative) => (
    alternative
    && typeof alternative === "object"
    && !Array.isArray(alternative)
    && alternative.type === "null"
    && Object.keys(alternative).length === 1
  ));
  if (nullIndex === -1) {
    return compacted;
  }
  const typed = alternatives[1 - nullIndex];
  if (
    !typed
    || typeof typed !== "object"
    || Array.isArray(typed)
    || typeof typed.type !== "string"
    || Object.hasOwn(typed, "const")
  ) return compacted;

  const { anyOf: _anyOf, ...outer } = compacted;
  const nullable = { ...outer, ...typed, type: [typed.type, "null"] };
  if (Array.isArray(typed.enum)) nullable.enum = [...typed.enum, null];
  return nullable;
}

const VALIDATION_ANNOTATION_KEYS = new Set([
  "$comment",
  "default",
  "deprecated",
  "description",
  "examples",
  "readOnly",
  "title",
  "writeOnly",
]);

function stripValidationAnnotations(value, parentKeyword = null) {
  if (Array.isArray(value)) {
    return value.map((item) => stripValidationAnnotations(item, parentKeyword));
  }
  if (!value || typeof value !== "object") return value;
  const isSchemaNameMap = parentKeyword === "$defs" || parentKeyword === "definitions"
    || parentKeyword === "dependentSchemas" || parentKeyword === "patternProperties"
    || parentKeyword === "properties";
  return Object.fromEntries(
    Object.entries(value)
      .filter(([key]) => isSchemaNameMap || !VALIDATION_ANNOTATION_KEYS.has(key))
      .map(([key, nestedValue]) => [key, stripValidationAnnotations(nestedValue, key)]),
  );
}

function withoutNestedTitles(value) {
  if (Array.isArray(value)) return value.map(withoutNestedTitles);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.entries(value)
      .filter(([key, nestedValue]) => key !== "title" || typeof nestedValue !== "string")
      .map(([key, nestedValue]) => [
        key,
        key === "properties" ? propertySchemasWithoutTitles(nestedValue) : withoutNestedTitles(nestedValue),
      ]),
  );
}

function propertySchemasWithoutTitles(properties) {
  return Object.fromEntries(
    Object.entries(properties).map(([name, propertySchema]) => [name, withoutNestedTitles(propertySchema)]),
  );
}

// Every contract root compiles into one declaration module, so a nested
// definition is declared once. Only definitions keep their titles: a property
// title would become an alias that json-schema-to-typescript numbers apart
// (Status, Status1, ...), so an unrelated addition would rename it.
function typeDeclarationSchema(schema, definitionNames) {
  const definitions = Object.fromEntries(
    Object.entries(schema.$defs).map(([name, definition]) => [
      name,
      { ...withoutNestedTitles(definition), ...(definition.title ? { title: definition.title } : {}) },
    ]),
  );
  return compactNullableSchemas({
    $schema: schema.$schema,
    title: TYPE_ROOT_NAME,
    type: "object",
    properties: Object.fromEntries(
      definitionNames.map((definitionName) => [definitionName, { $ref: `#/$defs/${definitionName}` }]),
    ),
    required: definitionNames,
    additionalProperties: false,
    $defs: definitions,
  });
}

function visitLocalDefinitionReferences(value, enqueue) {
  if (Array.isArray(value)) {
    value.forEach((item) => visitLocalDefinitionReferences(item, enqueue));
  } else if (value && typeof value === "object") {
    for (const [key, nestedValue] of Object.entries(value)) {
      if (key === "$ref" && typeof nestedValue === "string" && nestedValue.startsWith("#/$defs/")) {
        const definitionName = nestedValue.slice("#/$defs/".length);
        if (!definitionName || definitionName.includes("/")) {
          throw new Error(`Unsupported local definition reference: ${nestedValue}`);
        }
        enqueue(definitionName);
      } else visitLocalDefinitionReferences(nestedValue, enqueue);
    }
  }
}

export function extractContractSchema(schema, definitionName) {
  const reachable = reachableDefinitionNames(schema, definitionName);
  const definitions = Object.fromEntries(
    [...reachable]
      .filter((name) => name !== definitionName)
      .sort()
      .map((name) => [name, schema.$defs[name]]),
  );
  return {
    schema: stripValidationAnnotations(compactNullableSchemas({
      $schema: schema.$schema,
      $id: contractSchemaId(schema, definitionName),
      $defs: definitions,
      ...schema.$defs[definitionName],
    })),
    reachableDefinitionCount: reachable.size,
  };
}

/**
 * One schema holding every definition a module's contracts reach, so a
 * definition shared by several of them compiles to one validator function.
 */
export function extractModuleContractSchema(schema, module) {
  const reachable = new Set();
  for (const { definitionName } of module.validators) {
    for (const name of reachableDefinitionNames(schema, definitionName)) reachable.add(name);
  }
  return stripValidationAnnotations(compactNullableSchemas({
    $schema: schema.$schema,
    $id: contractSchemaId(schema, module.validatorFilename.replace(/\.validators\.mjs$/, "")),
    $defs: Object.fromEntries([...reachable].sort().map((name) => [name, schema.$defs[name]])),
  }));
}

function contractSchemaId(schema, name) {
  const schemaId = new URL(schema.$id);
  schemaId.pathname = `${schemaId.pathname.replace(/\.json$/, "")}/contracts/${name}.json`;
  schemaId.hash = "";
  return schemaId.href;
}

function reachableDefinitionNames(schema, definitionName) {
  if (!schema.$defs?.[definitionName]) {
    throw new Error(`Missing contract definition: ${definitionName}`);
  }
  const reachable = new Set();
  const pending = [definitionName];
  while (pending.length > 0) {
    const current = pending.shift();
    if (reachable.has(current)) continue;
    const definition = schema.$defs[current];
    if (!definition) {
      throw new Error(`Missing definition referenced by ${definitionName}: ${current}`);
    }
    reachable.add(current);
    visitLocalDefinitionReferences(definition, (reference) => pending.push(reference));
  }
  return reachable;
}

function requiredNode(schema, definitionName, ...segments) {
  let node = schema.$defs?.[definitionName];
  for (const segment of segments) node = node?.[segment];
  if (!node || typeof node !== "object") {
    throw new Error(`Missing schema node: #/$defs/${definitionName}/${segments.join("/")}`);
  }
  return node;
}

function requiredConst(schema, definitionName, ...segments) {
  const node = requiredNode(schema, definitionName, ...segments);
  if (!Object.hasOwn(node, "const")) {
    throw new Error(`Expected const at #/$defs/${definitionName}/${segments.join("/")}`);
  }
  return node.const;
}

function requiredEnum(schema, definitionName, ...segments) {
  const node = requiredNode(schema, definitionName, ...segments);
  if (!Array.isArray(node.enum)) {
    throw new Error(`Expected enum at #/$defs/${definitionName}/${segments.join("/")}`);
  }
  return node.enum;
}

function generateConstants(schema) {
  const values = [
    [
      "EXPLORE_CHART_CONFIG_VERSION",
      requiredConst(schema, "ExploreChartConfig", "properties", "version"),
    ],
    ["EXPLORE_CHART_MARK_VALUES", requiredEnum(schema, "ChartValueEncoding", "properties", "mark")],
    ["EXPLORE_CHART_AXIS_VALUES", requiredEnum(schema, "ChartValueEncoding", "properties", "axis")],
    [
      "EXPLORE_CHART_ORIENTATION_VALUES",
      requiredEnum(schema, "ExploreChartConfig", "properties", "orientation"),
    ],
    [
      "EXPLORE_CHART_NUMBER_FORMAT_VALUES",
      requiredEnum(schema, "ChartAxisConfig", "properties", "number_format"),
    ],
    [
      "EXPLORE_CHART_LEGEND_POSITION_VALUES",
      requiredEnum(schema, "ChartLegend", "properties", "position"),
    ],
  ];
  const declarations = values.map(
    ([name, value]) => `export const ${name} = ${JSON.stringify(value)} as const;`,
  );
  return withBanner(declarations.join("\n"));
}

function moduleConstants(schema, module) {
  return module.validators.flatMap(({ definitionName, constantExports }) =>
    (constantExports ?? []).map(({ name, path: valuePath }) => [
      name,
      requiredConst(schema, definitionName, ...valuePath),
    ]));
}

async function generateTypes(schema) {
  const definitionNames = validatorModules(schema).flatMap(({ validators }) =>
    validators.map(({ definitionName }) => definitionName));
  const declarations = await compile(typeDeclarationSchema(schema, definitionNames), TYPE_ROOT_NAME, {
    additionalProperties: false,
    bannerComment: "",
    // Array bounds stay in the validators; as types they would become tuple unions.
    ignoreMinAndMaxItems: true,
    style: { singleQuote: true },
  });
  // The synthetic root only gathers the contracts; nothing may use it.
  const rootPattern = new RegExp(`^export interface ${TYPE_ROOT_NAME} \\{\\n(?:  .*\\n)*\\}\\n`, "m");
  if (!rootPattern.test(declarations)) {
    throw new Error(`Generated declarations lack the ${TYPE_ROOT_NAME} root to remove`);
  }
  const contractDeclarations = declarations.replace(rootPattern, "");
  if (contractDeclarations.includes(TYPE_ROOT_NAME)) {
    throw new Error(`Generated declarations still reference ${TYPE_ROOT_NAME}`);
  }
  return withBanner(contractDeclarations);
}

function compactFailFastErrorMetadata(source) {
  const schemaPathPattern = /schemaPath:"(?:\\.|[^"\\])*",/g;
  const schemaPathCount = source.match(schemaPathPattern)?.length ?? 0;
  if (schemaPathCount === 0) {
    throw new Error("Ajv fail-fast source did not contain compactable schemaPath metadata");
  }
  const withoutSchemaPaths = source.replace(schemaPathPattern, "");
  if (withoutSchemaPaths.includes("schemaPath:")) {
    throw new Error("Ajv fail-fast source contains an unsupported schemaPath expression");
  }

  const nonRequiredParamsPattern = /keyword:"(?!required")([^"\\]+)",params:\{[^{}]*\}/g;
  const paramsCount = withoutSchemaPaths.match(nonRequiredParamsPattern)?.length ?? 0;
  if (paramsCount === 0) {
    throw new Error("Ajv fail-fast source did not contain compactable error parameters");
  }
  return withoutSchemaPaths.replace(
    nonRequiredParamsPattern,
    (_match, keyword) => `keyword:"${keyword}",params:{}`,
  );
}

async function generateValidator(schema, module) {
  const ajv = new Ajv2020({
    allErrors: module.allErrors,
    inlineRefs: false,
    loopRequired: module.allErrors ? 5 : 200,
    messages: module.allErrors,
    strict: true,
    code: { source: true, esm: true, optimize: 2 },
  });
  const exports = {};
  if (module.validators.length === 1) {
    const [{ definitionName, exportName }] = module.validators;
    const extracted = extractContractSchema(schema, definitionName);
    ajv.addSchema(extracted.schema);
    exports[exportName] = extracted.schema.$id;
  } else {
    const moduleSchema = extractModuleContractSchema(schema, module);
    ajv.addSchema(moduleSchema);
    for (const { definitionName, exportName } of module.validators) {
      exports[exportName] = `${moduleSchema.$id}#/$defs/${definitionName}`;
    }
  }
  const standalone = standaloneCode(ajv, exports);
  const validatorSource = module.allErrors
    ? standalone
    : compactFailFastErrorMetadata(standalone);
  const bundled = await build({
    absWorkingDir: FRONTEND_DIRECTORY,
    bundle: true,
    format: "esm",
    minify: true,
    platform: "browser",
    target: "es2022",
    write: false,
    stdin: { contents: validatorSource, loader: "js", sourcefile: module.validatorFilename },
    plugins: [{ name: "bundle-ajv-runtime", setup(buildContext) {
      buildContext.onResolve(
        { filter: /^ajv\/dist\/runtime\// },
        ({ path: runtimePath }) => ({ path: require.resolve(runtimePath) }),
      );
    } }],
  });
  if (bundled.outputFiles.length !== 1) {
    throw new Error(`Expected one bundled validator output for ${module.validatorFilename}`);
  }
  const constants = moduleConstants(schema, module).map(
    ([name, value]) => `export const ${name} = ${JSON.stringify(value)};`,
  );
  return withBanner([bundled.outputFiles[0].text, ...constants].join("\n"));
}

function generateValidatorDeclaration(schema, module) {
  const schemaPath = module.allErrors
    ? "readonly schemaPath: string;"
    : "readonly schemaPath?: string;";
  const errors = [
    "readonly { readonly instancePath: string;",
    schemaPath,
    "readonly keyword: string; readonly params: Record<string, unknown>;",
    "readonly message?: string }[] | null",
  ].join(" ");
  const constants = moduleConstants(schema, module).map(
    ([name, value]) => `export declare const ${name}: ${JSON.stringify(value)};`,
  );
  const definitionNames = module.validators.map(({ definitionName }) => definitionName);
  const validators = module.validators.map(({ definitionName, exportName }) => `export declare const ${exportName}: {
  (data: unknown): data is ${definitionName};
  readonly errors: ${errors};
};`);
  return withBanner(`import type { ${definitionNames.join(", ")} } from './api-contracts.generated';

${[...validators, ...constants].join("\n")}`);
}

export async function buildArtifacts(outputDirectory = DEFAULT_OUTPUT_DIRECTORY) {
  const schema = JSON.parse(await readFile(path.join(outputDirectory, SCHEMA_FILENAME), "utf8"));
  const artifacts = new Map([
    [GENERATED_TYPES_FILENAME, await generateTypes(schema)],
    [CONSTANTS_FILENAME, generateConstants(schema)],
  ]);
  for (const module of validatorModules(schema)) {
    artifacts.set(module.validatorFilename, await generateValidator(schema, module));
    artifacts.set(module.declarationFilename, generateValidatorDeclaration(schema, module));
  }
  return artifacts;
}

async function hasSameContents(filename, contents) {
  try { return (await readFile(filename, "utf8")) === contents; }
  catch (error) { if (error.code === "ENOENT") return false; throw error; }
}

async function writeAtomically(filename, contents) {
  if (await hasSameContents(filename, contents)) return false;
  await mkdir(path.dirname(filename), { recursive: true });
  const temporary = `${filename}.${process.pid}.${Date.now()}.tmp`;
  try { await writeFile(temporary, contents, "utf8"); await rename(temporary, filename); }
  finally {
    await unlink(temporary).catch((error) => {
      if (error.code !== "ENOENT") throw error;
    });
  }
  return true;
}

export async function run({
  check = false,
  outputDirectory = DEFAULT_OUTPUT_DIRECTORY,
  report = true,
} = {}) {
  const artifacts = await buildArtifacts(outputDirectory);
  const stale = [];
  for (const [name, contents] of artifacts) {
    if (!(await hasSameContents(path.join(outputDirectory, name), contents))) {
      stale.push(name);
    }
  }
  if (check) {
    if (stale.length > 0 && report) {
      console.error(`Stale or missing API contract artifacts: ${stale.join(", ")}`);
    }
    return stale.length === 0;
  }
  for (const [name, contents] of artifacts) {
    await writeAtomically(path.join(outputDirectory, name), contents);
  }
  return true;
}

export { CONSTANTS_FILENAME, DEFAULT_OUTPUT_DIRECTORY, GENERATED_TYPES_FILENAME, SCHEMA_FILENAME };

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const options = parseOptions(process.argv.slice(2));
  run(options)
    .then((success) => {
      if (!success) process.exitCode = 1;
    })
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    });
}
