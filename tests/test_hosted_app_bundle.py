"""The hosted Databricks app's bundle: its lock, its wheel and its boot (BUG-40).

The build resolves haute's runtime for the app's platform into a hashed lock and
records the wheel it built; the boot installs exactly the lock and the checked wheel,
resolving nothing; the deploy ships the build's outputs to the app it names. The
shell scripts run under the bash a CI runner would use, with ``uv`` and
``databricks`` stood in by exported functions that record each call.
"""

from __future__ import annotations

import hashlib
import importlib.util
import os
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest

from tests._posix_shell import posix_shell

_REPO_ROOT = Path(__file__).resolve().parents[1]
_APP_DIR = _REPO_ROOT / "databricks_app"
_HASH = "a" * 64

# Each records its arguments, one call to a line, in $CALLS. The fake uv builds the
# wheel $FAKE_VERSION names (and $FAKE_EXTRA's too, when set) and writes a lock whose
# index line carries a credential, as uv's --emit-index-url does.
_FAKE_CLIS = r"""
uv() {
  printf 'uv %s\n' "$*" >> "$CALLS"
  case "$1" in
    --version) echo "uv 9.9.9" ;;
    build)
      local out=""
      while [ $# -gt 0 ]; do [ "$1" = "--out-dir" ] && out="$2"; shift; done
      printf 'wheel %s' "$FAKE_VERSION" > "$out/haute-$FAKE_VERSION-py3-none-any.whl"
      if [ -n "${FAKE_EXTRA:-}" ]; then
        printf 'wheel %s' "$FAKE_EXTRA" > "$out/haute-$FAKE_EXTRA-py3-none-any.whl"
      fi
      ;;
    pip)
      local lock=""
      while [ $# -gt 0 ]; do [ "$1" = "-o" ] && lock="$2"; shift; done
      {
        echo "# This file was autogenerated by uv via the following command:"
        echo "#    databricks_app/scripts/build_bundle.sh"
        echo "--index-url https://user:s3cret@mirror.example.com/simple"
        echo ""
        printf 'polars==2.0.0 \\\n    --hash=sha256:%s\n' "$FAKE_HASH"
        printf '    # via haute (pyproject.toml)\n'
        printf 'pyarrow==24.0.0 \\\n    --hash=sha256:%s\n' "$FAKE_HASH"
      } > "$lock"
      ;;
  esac
}
databricks() { printf 'databricks %s\n' "$*" >> "$CALLS"; }
export -f uv databricks
"""


def _repository(tmp_path: Path, *, stale: list[str]) -> Path:
    """A repository with the app bundle's scripts, older builds left in dist/ and the
    wheel a previous bundle shipped."""
    repo = tmp_path / "repo"
    (repo / "databricks_app" / "scripts").mkdir(parents=True)
    for script in ("build_bundle.sh", "deploy.sh"):
        target = repo / "databricks_app" / "scripts" / script
        target.write_bytes((_APP_DIR / "scripts" / script).read_bytes())
    (repo / "pyproject.toml").write_text('[project]\nname = "haute"\n', encoding="utf-8")
    (repo / "dist").mkdir()
    for version in stale:
        (repo / "dist" / f"haute-{version}-py3-none-any.whl").write_text(
            f"old {version}", encoding="utf-8"
        )
    previous = repo / "databricks_app" / "haute-0.0.1-py3-none-any.whl"
    previous.write_text("previous bundle", encoding="utf-8")
    return repo


def _run(
    repo: Path, tmp_path: Path, script: str, *arguments: str, version: str, extra: str = ""
) -> tuple[subprocess.CompletedProcess[str], list[str]]:
    calls = tmp_path / "calls.txt"
    # A file, not ``-c``: the Windows command line would drop one of the fake's backslashes.
    driver = tmp_path / "driver.sh"
    driver.write_bytes((_FAKE_CLIS + 'script="$1"; shift; bash "$script" "$@"\n').encode())
    result = subprocess.run(
        [
            posix_shell(),
            driver.as_posix(),
            (repo / "databricks_app" / "scripts" / script).as_posix(),
            *arguments,
        ],
        env={
            **os.environ,
            "CALLS": calls.as_posix(),
            "FAKE_VERSION": version,
            "FAKE_EXTRA": extra,
            "FAKE_HASH": _HASH,
            "HAUTE_BUILD_FRONTEND": "0",
        },
        capture_output=True,
        text=True,
        check=False,
    )
    recorded = calls.read_text(encoding="utf-8").splitlines() if calls.exists() else []
    return result, recorded


@pytest.mark.parametrize(
    ("version", "stale"),
    [
        pytest.param("0.10.0", ["0.9.0"], id="newer-beside-stale"),
        pytest.param("0.9.0", ["0.10.0"], id="lower-rebuild"),
    ],
)
def test_the_bundle_holds_the_wheel_just_built(
    tmp_path: Path, version: str, stale: list[str]
) -> None:
    """The bundle took the lexicographically last wheel in a shared dist/, so a stale
    0.9.0 shipped beside a fresh 0.10.0, and a stale 0.10.0 beside a 0.9.0 rebuild."""
    repo = _repository(tmp_path, stale=stale)

    result, _calls = _run(repo, tmp_path, "build_bundle.sh", version=version)

    assert result.returncode == 0, result.stderr
    bundle = repo / "databricks_app"
    wheel = bundle / f"haute-{version}-py3-none-any.whl"
    assert [path.name for path in bundle.glob("haute-*.whl")] == [wheel.name]
    assert wheel.read_text(encoding="utf-8") == f"wheel {version}"
    digest = hashlib.sha256(wheel.read_bytes()).hexdigest()
    assert (bundle / "wheel.sha256").read_text(encoding="utf-8") == f"{digest}  {wheel.name}\n"


def test_a_build_that_makes_more_than_one_wheel_is_refused(tmp_path: Path) -> None:
    repo = _repository(tmp_path, stale=[])

    result, _calls = _run(repo, tmp_path, "build_bundle.sh", version="0.6.0", extra="0.5.0")

    assert result.returncode != 0
    assert "exactly one haute wheel" in result.stderr
    assert not (repo / "databricks_app" / "requirements.txt").exists()


def test_the_lock_is_resolved_for_the_app_hashed_and_free_of_credentials(
    tmp_path: Path,
) -> None:
    repo = _repository(tmp_path, stale=[])

    result, calls = _run(repo, tmp_path, "build_bundle.sh", version="0.6.0")

    assert result.returncode == 0, result.stderr
    (compiled,) = [call for call in calls if call.startswith("uv pip compile ")]
    for option in (
        "--extra databricks",
        "--python-version 3.11",
        "--python-platform x86_64-manylinux_2_28",
        "--generate-hashes",
    ):
        assert option in compiled
    lines = (repo / "databricks_app" / "requirements.txt").read_text(encoding="utf-8").splitlines()
    assert not any("@" in line for line in lines)
    assert "# resolved from --index-url https://mirror.example.com/simple" in lines
    assert "# resolved by uv 9.9.9 for CPython 3.11 on x86_64-manylinux_2_28." in lines
    pins = [index for index, line in enumerate(lines) if "==" in line]
    assert len(pins) == 2
    assert all(lines[index + 1].strip() == f"--hash=sha256:{_HASH}" for index in pins)


def test_deploy_ships_the_build_outputs_to_the_app_it_names(tmp_path: Path) -> None:
    repo = _repository(tmp_path, stale=[])
    workspace = "/Users/someone@example.com/pricing-app"

    result, calls = _run(
        repo, tmp_path, "deploy.sh", "my-profile", workspace, "pricing-app", version="0.6.0"
    )

    assert result.returncode == 0, result.stderr
    databricks = [call for call in calls if call.startswith("databricks ")]
    assert databricks[0].startswith("databricks sync ")
    # Sync honours .gitignore, which keeps every build output out of git.
    imported = sorted(
        call.split(" --overwrite ")[1].split()[0]
        for call in databricks
        if call.startswith("databricks workspace import ")
    )
    assert imported == [
        f"{workspace}/haute-0.6.0-py3-none-any.whl",
        f"{workspace}/requirements.txt",
        f"{workspace}/wheel.sha256",
    ]
    assert databricks[-1] == (
        f"databricks apps deploy pricing-app --source-code-path /Workspace{workspace} "
        "--profile my-profile"
    )


def test_the_build_outputs_are_never_committed() -> None:
    for name in ("requirements.txt", "wheel.sha256", "haute-0.6.0-py3-none-any.whl"):
        ignored = subprocess.run(
            ["git", "check-ignore", "-q", f"databricks_app/{name}"], cwd=_REPO_ROOT, check=False
        )
        assert ignored.returncode == 0, name
    tracked = subprocess.run(
        ["git", "ls-files", "databricks_app"],
        cwd=_REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.split()
    assert "databricks_app/requirements.txt" not in tracked


def _app() -> ModuleType:
    """``databricks_app/app.py``, loaded under a name of its own."""
    spec = importlib.util.spec_from_file_location("databricks_app_entry", _APP_DIR / "app.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _bundle(tmp_path: Path, *, recorded: str | None = None) -> Path:
    bundle = tmp_path / "bundle"
    bundle.mkdir()
    (bundle / "haute-0.6.0-py3-none-any.whl").write_bytes(b"wheel bytes")
    digest = recorded or hashlib.sha256(b"wheel bytes").hexdigest()
    (bundle / "wheel.sha256").write_text(
        f"{digest}  haute-0.6.0-py3-none-any.whl\n", encoding="utf-8"
    )
    (bundle / "requirements.txt").write_text(
        f"polars==2.0.0 \\\n    --hash=sha256:{_HASH}\n", encoding="utf-8"
    )
    return bundle


def _recorded_pip(monkeypatch: pytest.MonkeyPatch, app: ModuleType) -> list[list[str]]:
    commands: list[list[str]] = []

    def run(command: list[str], *, check: bool) -> None:
        assert check
        commands.append(command)

    monkeypatch.setattr(app.subprocess, "run", run)
    return commands


def test_boot_installs_the_lock_and_the_checked_wheel_resolving_nothing(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Every boot ran ``pip install <wheel>[databricks]``, resolving haute's ranges from
    the index, so two boots of one deployment could run different dependencies."""
    app = _app()
    commands = _recorded_pip(monkeypatch, app)
    bundle = _bundle(tmp_path)

    app._install_locked_runtime(bundle)

    pip = [sys.executable, "-m", "pip", "--disable-pip-version-check", "install", "--no-deps"]
    assert commands == [
        [*pip, "--require-hashes", "-r", str(bundle / "requirements.txt")],
        [*pip, "--force-reinstall", str(bundle / "haute-0.6.0-py3-none-any.whl")],
    ]


def test_a_wheel_unlike_its_recorded_digest_stops_the_boot(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    app = _app()
    commands = _recorded_pip(monkeypatch, app)

    with pytest.raises(RuntimeError, match="does not match wheel.sha256"):
        app._install_locked_runtime(_bundle(tmp_path, recorded="0" * 64))

    assert commands == []


def test_a_bundle_without_one_wheel_stops_the_boot(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    app = _app()
    commands = _recorded_pip(monkeypatch, app)
    bundle = _bundle(tmp_path)
    (tmp_path / "bundle" / "haute-0.5.0-py3-none-any.whl").write_bytes(b"older")

    with pytest.raises(RuntimeError, match="exactly one vendored haute wheel"):
        app._install_locked_runtime(bundle)

    assert commands == []
