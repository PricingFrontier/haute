# Test 3: Unsupported and window forms classification
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "expr_text",
    [
        'pl.col("x").sum().over("y")',
        'pl.col("x").over("y")',
        'pl.col("x").shift(1)',
        'pl.col("x").diff()',
        'pl.col("x").mean()',
    ],
)
def test_receiver_value_window_forms_classified(expr_text: str) -> None:
    row = {"x": 42.0, "y": 1, "s": "abc"}
    actual = _trace_value(expr_text, row)
    assert actual == 42.0


@pytest.mark.parametrize(
    "expr_text",
    [
        'pl.col("x").cum_sum()',
        'pl.col("x").rolling_mean(2)',
        'pl.col("x").str.slice(1)',
    ],
)
def test_unsupported_forms_return_none(expr_text: str) -> None:
    row = {"x": 42.0, "y": 1, "s": "abc"}
    actual = _trace_value(expr_text, row)
    assert actual is None


def test_window_semantics_diverge_from_single_row_approximation() -> None:
    two_row_df = pl.DataFrame({"x": [10.0, 20.0], "y": [1, 1]})
    polars_window = two_row_df.select(pl.col("x").sum().over("y"))["x"].to_list()
    assert polars_window == [30.0, 30.0]
    assert polars_window != [10.0, 20.0]
