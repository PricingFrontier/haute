"""Property-based parity tests pinning Haute's _ExprEvaluator to real Polars.

Verifies that for every expression in a bounded grammar of documented, well-formed
single-row operations, the evaluator's result_value agrees with real Polars on
the same one-row frame (ENG-T11, closing the "no property-based testing" gap in
specs/expression-parsing/low-level.md).

Domain: numeric, boolean and string expressions of depth at most three over the
columns x and y (int, float or null) and s (string or null), built only from the
forms the evaluator documents. The one-row frame types a null cell by the value
family (Int64 for ints, Float64 for floats and nulls, String for s) so null
propagation is exercised through every operation instead of tripping Polars'
Null-dtype rejections. Malformed calls, window/aggregation forms and
unsupported methods are outside the domain; the classification tests below pin
their documented placeholder behaviour instead. A Polars evaluation that raises
on a generated form is assumed away; with the typed frame that happened for
none of 600 sampled examples on 2026-09-06.
"""

from __future__ import annotations

import ast
import math

import hypothesis.strategies as st
import polars as pl
import pytest
from hypothesis import assume, example, find, given

from haute._expression_parser import evaluate_expression
from tests._property_budget import pr_budget


def _trace_value(expr_text: str, row: dict) -> object:
    """result_value the trace renders for df.with_columns(<expr>.alias("out"))."""
    code = f'df = df.with_columns({expr_text}.alias("out"))'
    return evaluate_expression(code, "out", dict(row)).result_value


def _column_dtype(value: object) -> pl.DataType:
    """Type a one-row cell the way a real frame column would be typed."""
    if isinstance(value, bool):
        return pl.Boolean
    if isinstance(value, int):
        return pl.Int64
    if isinstance(value, str):
        return pl.String
    return pl.Float64


def _polars_value(expr_text: str, row: dict) -> object:
    """The engine's actual output for the same expression on a one-row frame.

    ``expr_text`` is generated by this module's own grammar (never user input),
    so ``eval`` is safe here. A null cell takes the numeric dtype of its column
    family (``s`` stays String) because a production frame carries a typed
    column with a null, not a Null-typed column.
    """
    expr = eval(expr_text, {"pl": pl})
    schema = {
        name: (pl.String if name == "s" else _column_dtype(value)) for name, value in row.items()
    }
    return pl.DataFrame([dict(row)], schema=schema).select(expr.alias("out")).item()


def values_equivalent(a: object, b: object) -> bool:
    """Check equivalence between evaluator trace value and Polars value.

    Equivalence rules:
    - both None -> equal
    - both bool -> ==
    - numbers (int/float) -> math.isclose(a, b, rel_tol=1e-9, abs_tol=1e-9)
      with NaN equal to NaN and infinities compared by identity/sign
    - strings -> ==
    - anything else -> ==
    """
    if a is None and b is None:
        return True
    if a is None or b is None:
        return False
    if isinstance(a, bool) or isinstance(b, bool):
        return isinstance(a, bool) and isinstance(b, bool) and a == b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        if math.isnan(a) and math.isnan(b):
            return True
        if math.isnan(a) or math.isnan(b):
            return False
        if math.isinf(a) and math.isinf(b):
            return (a > 0) == (b > 0)
        if math.isinf(a) or math.isinf(b):
            return False
        return math.isclose(a, b, rel_tol=1e-9, abs_tol=1e-9)
    if isinstance(a, str) and isinstance(b, str):
        return a == b
    return a == b


