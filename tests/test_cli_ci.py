def test_the_deploys_secrets_are_set_from_env(runner, project: Path) -> None:
    _env_file(project, _VALUES)
    gh = _Gh()

    result, checked = _invoke(runner, ["secrets"], gh)

    assert result.exit_code == 0, result.output
    assert gh.secrets == _VALUES
    # Each value reaches gh on its standard input, never its arguments or the output.
    for command, stdin in gh.calls:
        assert command[:2] == ["secret", "set"]
        assert stdin == _VALUES[command[2]]
    for value in ("dapi-mlflow-secret", "dapi-rating-secret"):
        assert value not in result.output
    assert "DATABRICKS_RATING_TOKEN (from .env)" in result.output
    # Both pairs were checked against the workspace before anything was set.
    assert [call.args for call in checked.call_args_list] == [
        (_VALUES["DATABRICKS_MLFLOW_HOST"], "dapi-mlflow-secret"),
        (_VALUES["DATABRICKS_RATING_HOST"], "dapi-rating-secret"),
    ]


