"""``haute ci``: the deploy's CI secrets set from ``.env``, and the generated CI files kept up.

A new project's first staging deploy failed because the repository had none of the
secrets its workflow reads; ``haute ci secrets`` sets them from ``.env`` through the
GitHub CLI, checking Databricks accepts them first. A project generated by an older
haute kept that haute's workflows; ``haute ci update`` rewrites them.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path
from typing import Any
from unittest.mock import patch

import pytest

from haute._scaffold import ci_files, env_example
from haute.cli import cli

_VALUES = {
    "DATABRICKS_MLFLOW_HOST": "https://adb-9.azuredatabricks.net",
    "DATABRICKS_MLFLOW_TOKEN": "dapi-mlflow-secret",
    "DATABRICKS_RATING_HOST": "https://adb-9.azuredatabricks.net",
    "DATABRICKS_RATING_TOKEN": "dapi-rating-secret",
}


@pytest.fixture
def project(runner, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A Databricks project on GitHub, as ``haute init`` makes it, with no credentials."""
    monkeypatch.chdir(tmp_path)
    for name in _VALUES:
        monkeypatch.delenv(name, raising=False)
    result = runner.invoke(cli, ["init", "--target", "databricks", "--ci", "github"])
    assert result.exit_code == 0, result.output
    return tmp_path


def _env_file(project: Path, values: dict[str, str]) -> None:
    (project / ".env").write_text(
        "".join(f"{name}={value}\n" for name, value in values.items()), encoding="utf-8"
    )


class _Gh:
    """``gh`` as ``subprocess.run`` runs it: the repository's secrets, and every call."""

    def __init__(self, existing: tuple[str, ...] = (), fail_set: str | None = None) -> None:
        self.secrets: dict[str, str] = dict.fromkeys(existing, "set before")
        self.calls: list[tuple[list[str], str | None]] = []
        self.fail_set = fail_set

    def __call__(self, args: list[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
        command, stdin = list(args[1:]), kwargs["input"]
        self.calls.append((command, stdin))
        if command[:2] == ["secret", "list"]:
            listed = json.dumps([{"name": name} for name in self.secrets])
            return subprocess.CompletedProcess(args, 0, listed, "")
        if command[:2] == ["secret", "set"]:
            if command[2] == self.fail_set:
                return subprocess.CompletedProcess(args, 1, "", "HTTP 403: Resource not accessible")
            self.secrets[command[2]] = stdin
            return subprocess.CompletedProcess(args, 0, "", "")
        raise AssertionError(f"unexpected gh call: {command}")


def _invoke(runner, args: list[str], gh: _Gh, *, refuse: Exception | None = None) -> Any:
    def user(host: str, token: str) -> str:
        if refuse is not None:
            raise refuse
        return "ci-bot@example.com"

    with (
        patch("haute.cli._ci.shutil.which", return_value="/usr/bin/gh"),
        patch("haute.cli._ci.subprocess.run", side_effect=gh),
        patch("haute.deploy._databricks_serving.workspace_user", side_effect=user) as checked,
    ):
        result = runner.invoke(cli, ["ci", *args])
    return result, checked


