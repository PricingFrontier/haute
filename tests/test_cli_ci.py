@pytest.mark.parametrize(("ci", "command"), [("github", True), ("gitlab", False)])
def test_init_names_the_secrets_the_first_deploy_needs(
    runner, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, ci: str, command: bool
) -> None:
    monkeypatch.chdir(tmp_path)

    result = runner.invoke(cli, ["init", "--ci", ci])

    assert result.exit_code == 0, result.output
    assert f"Before the first deploy, {ci} needs these CI secrets:" in result.output
    for name in _VALUES:
        assert name in result.output
    assert ("haute ci secrets" in result.output) is command
