def test_the_deploys_secrets_are_set_from_env(runner, project: Path) -> None:
    _env_file(project, _VALUES)
    gh = _Gh()

    result, checked = _invoke(runner, ["secrets"], gh)

    assert result.exit_code == 0, result.output
    assert gh.secrets == _VALUES
    # Each value reaches gh on its standard input, never its arguments or the output.
    for command, stdin in gh.calls:
        assert command[:2] == ["secret", "set"]
        assert stdin == _VALUES[command[2]]
    for value in ("dapi-mlflow-secret", "dapi-rating-secret"):
        assert value not in result.output
    assert "DATABRICKS_RATING_TOKEN (from .env)" in result.output
    # Both pairs were checked against the workspace before anything was set.
    assert [call.args for call in checked.call_args_list] == [
        (_VALUES["DATABRICKS_MLFLOW_HOST"], "dapi-mlflow-secret"),
        (_VALUES["DATABRICKS_RATING_HOST"], "dapi-rating-secret"),
    ]


def test_env_wins_over_the_environment_which_fills_its_gaps(
    runner, project: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _env_file(project, {k: v for k, v in _VALUES.items() if k != "DATABRICKS_RATING_HOST"})
    monkeypatch.setenv("DATABRICKS_RATING_HOST", "https://from-shell.example")
    monkeypatch.setenv("DATABRICKS_MLFLOW_TOKEN", "shell-token")
    gh = _Gh()

    result, _ = _invoke(runner, ["secrets"], gh)

    assert result.exit_code == 0, result.output
    assert gh.secrets["DATABRICKS_MLFLOW_TOKEN"] == "dapi-mlflow-secret"
    assert gh.secrets["DATABRICKS_RATING_HOST"] == "https://from-shell.example"
    assert "DATABRICKS_RATING_HOST (from the environment)" in result.output


def test_an_unset_secret_sets_nothing(runner, project: Path) -> None:
    _env_file(project, {k: v for k, v in _VALUES.items() if k != "DATABRICKS_RATING_TOKEN"})
    gh = _Gh()

    result, checked = _invoke(runner, ["secrets"], gh)

    assert result.exit_code == 1
    assert "Not set in .env or the environment: DATABRICKS_RATING_TOKEN" in result.output
    assert gh.calls == []
    checked.assert_not_called()


def test_an_unedited_env_example_sets_nothing(runner, project: Path) -> None:
    (project / ".env").write_text(
        (project / ".env.example").read_text(encoding="utf-8"), encoding="utf-8"
    )
    gh = _Gh()

    result, _ = _invoke(runner, ["secrets"], gh)

    assert result.exit_code == 1
    assert "Still .env.example's placeholder: " + ", ".join(_VALUES) in result.output
    assert gh.calls == []


def test_credentials_databricks_refuses_set_nothing(runner, project: Path) -> None:
    _env_file(project, _VALUES)
    gh = _Gh()

    result, _ = _invoke(
        runner, ["secrets"], gh, refuse=PermissionError("Invalid token dapi-mlflow-secret")
    )

    assert result.exit_code == 1
    assert "Databricks refused DATABRICKS_MLFLOW_HOST and DATABRICKS_MLFLOW_TOKEN" in result.output
    assert "dapi-mlflow-secret" not in result.output
    assert gh.calls == []


def test_no_verify_sets_the_secrets_unchecked(runner, project: Path) -> None:
    _env_file(project, _VALUES)
    gh = _Gh()

    result, checked = _invoke(runner, ["secrets", "--no-verify"], gh)

    assert result.exit_code == 0, result.output
    assert gh.secrets == _VALUES
    checked.assert_not_called()


def test_a_secret_gh_cannot_set_fails_the_command(runner, project: Path) -> None:
    _env_file(project, _VALUES)
    gh = _Gh(fail_set="DATABRICKS_RATING_HOST")

    result, _ = _invoke(runner, ["secrets"], gh)

    assert result.exit_code == 1
    assert "HTTP 403: Resource not accessible" in result.output


def test_check_names_each_missing_secret(runner, project: Path) -> None:
    gh = _Gh(existing=("DATABRICKS_MLFLOW_HOST", "DATABRICKS_MLFLOW_TOKEN"))

    result, _ = _invoke(runner, ["secrets", "--check"], gh)

    assert result.exit_code == 1
    assert "✓ DATABRICKS_MLFLOW_TOKEN" in result.output
    assert "✗ DATABRICKS_RATING_HOST" in result.output
    assert "missing 2 of the 4 secrets" in result.output
    assert [command for command, _ in gh.calls] == [["secret", "list", "--json", "name"]]


def test_check_passes_when_every_secret_is_set(runner, project: Path) -> None:
    result, _ = _invoke(runner, ["secrets", "--check"], _Gh(existing=tuple(_VALUES)))

    assert result.exit_code == 0, result.output
    assert "All 4 secrets the deploy needs are set." in result.output


def test_without_the_github_cli_says_how_to_get_it(runner, project: Path) -> None:
    with patch("haute.cli._ci.shutil.which", return_value=None):
        result = runner.invoke(cli, ["ci", "secrets"])

    assert result.exit_code == 1
    assert "https://cli.github.com" in result.output


def test_another_provider_is_given_the_names_to_add(
    runner, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.chdir(tmp_path)
    assert runner.invoke(cli, ["init", "--ci", "gitlab"]).exit_code == 0

    result = runner.invoke(cli, ["ci", "secrets"])

    assert result.exit_code == 1
    assert "this project's CI provider is gitlab" in result.output
    assert "deployment/ci/gitlab/" in result.output
    for name in _VALUES:
        assert name in result.output


