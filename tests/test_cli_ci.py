def test_update_rewrites_the_generated_files(runner, project: Path) -> None:
    staging = project / ".github" / "workflows" / "deploy-staging.yml"
    staging.write_text("name: edited\n", encoding="utf-8")
    (project / ".env.example").unlink()

    result = runner.invoke(cli, ["ci", "update"])

    assert result.exit_code == 0, result.output
    expected = ci_files("databricks", "github", python_version="3.11")
    assert staging.read_text(encoding="utf-8") == expected[".github/workflows/deploy-staging.yml"]
    assert (project / ".env.example").read_text(encoding="utf-8") == env_example("databricks")
    assert "updated   .github/workflows/deploy-staging.yml" in result.output
    assert "updated   .env.example" in result.output
    assert "unchanged .github/workflows/ci.yml" in result.output


def test_update_follows_a_change_of_provider(runner, project: Path) -> None:
    toml = project / "haute.toml"
    toml.write_text(
        toml.read_text(encoding="utf-8").replace('provider = "github"', 'provider = "gitlab"'),
        encoding="utf-8",
    )

    result = runner.invoke(cli, ["ci", "update"])

    assert result.exit_code == 0, result.output
    assert (project / ".gitlab-ci.yml").is_file()
    assert not (project / ".github").exists()


def test_update_outside_a_project_fails(runner, tmp_path: Path, monkeypatch) -> None:
    monkeypatch.chdir(tmp_path)

    result = runner.invoke(cli, ["ci", "update"])

    assert result.exit_code == 1
    assert "No haute.toml found" in result.output


